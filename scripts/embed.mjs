#!/usr/bin/env node
/**
 * Embeds Luau sources into a generated module so the Luau CLI test runner can
 * build a simulated Roblox tree without filesystem access (the CLI has no io
 * library).
 *
 * Output is written to the target given as the first argument.
 */
import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import { join, relative, dirname, sep } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const outPath = process.argv[2] ?? join(repoRoot, "tests/cli/generated/AllModules.luau");
const roots = ["src", "tests/support", "tests/spec", "benchmarks"];

const files = [];
function walk(dir) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    const stat = statSync(full);
    if (stat.isDirectory()) walk(full);
    else if (entry.endsWith(".luau")) files.push(relative(repoRoot, full).split(sep).join("/"));
  }
}
for (const root of roots) walk(join(repoRoot, root));
files.sort();

function longString(source) {
  let level = 0;
  while (source.includes("]" + "=".repeat(level) + "]")) level += 1;
  const open = "[" + "=".repeat(level) + "[";
  const close = "]" + "=".repeat(level) + "]";
  return open + "\n" + source + "\n" + close;
}

const chunks = files.map((file) => {
  const source = readFileSync(join(repoRoot, file), "utf8");
  return `\t[${JSON.stringify(file)}] = ${longString(source)},`;
});

const output = `--!nocheck
-- Generated by scripts/embed.mjs. Do not edit by hand.
return {
${chunks.join("\n")}
}
`;

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, output);
console.log(`embedded ${files.length} Luau files -> ${relative(repoRoot, outPath)}`);
